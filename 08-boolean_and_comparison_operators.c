#include <stdio.h>
#include <stdbool.h>

int main(){
    
    int a = 5, b = 10;

    // Comparison Operators
    printf("a == b: %d\n", a == b);
    printf("a != b: %d\n", a != b);
    printf("a > b: %d\n", a > b);
    printf("a < b: %d\n", a < b);
    printf("a >= b: %d\n", a >= b);
    printf("a <= b: %d\n", a <= b);

    // Boolean Variables
    bool isTrue = true;
    bool isFalse = false;
    printf("isTrue: %d\n", isTrue);
    printf("isFalse: %d\n", isFalse);

    return 0;
}